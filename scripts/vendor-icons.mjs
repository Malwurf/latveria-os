#!/usr/bin/env node
// Vendors Material Icon Theme (MIT) into the Files mod: the dark icons its manifest names, the
// licence, and a trimmed manifest as a JS module (mods cannot read a JSON file synchronously).
// Usage: node scripts/vendor-icons.mjs <extracted npm package folder>
import { copyFileSync, existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { basename, join } from "node:path";
import { fileURLToPath } from "node:url";

const MAPS = ["fileNames", "fileExtensions", "folderNames", "folderNamesExpanded"];

export function trimManifest(manifest, version) {
  const icon = (id) => {
    const def = manifest.iconDefinitions[id];
    if (!def) throw new Error(`manifest names an undefined icon: ${id}`);
    return basename(def.iconPath, ".svg");
  };
  const out = { version, file: icon(manifest.file), folder: icon(manifest.folder), folderExpanded: icon(manifest.folderExpanded) };
  for (const map of MAPS) {
    out[map] = {};
    for (const [key, id] of Object.entries(manifest[map] ?? {})) {
      const lower = key.toLowerCase();
      if (!Object.hasOwn(out[map], lower)) out[map][lower] = icon(id);
    }
  }
  return out;
}

const iconsOf = (t) => [...new Set([t.file, t.folder, t.folderExpanded, ...MAPS.flatMap((m) => Object.values(t[m]))])].sort();

export function vendor({ pkg, mod }) {
  const icons = join(mod, "icons", "material");
  const manifestFile = join(mod, "material-icons.js");
  for (const p of [icons, manifestFile]) if (existsSync(p)) throw new Error(`${p} already exists; move it away first`);
  const { version } = JSON.parse(readFileSync(join(pkg, "package.json"), "utf8"));
  const trimmed = trimManifest(JSON.parse(readFileSync(join(pkg, "dist", "material-icons.json"), "utf8")), version);
  mkdirSync(icons, { recursive: true });
  const names = iconsOf(trimmed);
  for (const name of names) copyFileSync(join(pkg, "icons", `${name}.svg`), join(icons, `${name}.svg`));
  copyFileSync(join(pkg, "LICENSE"), join(icons, "LICENSE"));
  writeFileSync(manifestFile, `// Generated by scripts/vendor-icons.mjs from material-icon-theme ${version} (MIT). Do not edit.\n`
    + `export default ${JSON.stringify(trimmed)};\n`);
  return { version, icons: names.length };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const pkg = process.argv[2];
  if (!pkg) {
    console.error("usage: node scripts/vendor-icons.mjs <extracted npm package folder>");
    process.exit(2);
  }
  console.log(vendor({ pkg, mod: fileURLToPath(new URL("../mods/latveria-files/", import.meta.url)) }));
}
